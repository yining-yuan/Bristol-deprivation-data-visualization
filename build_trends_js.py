#!/usr/bin/env python3
# =============================================================================
# build_trends_js.py
# -----------------------------------------------------------------------------
# Reads bristol_trends.csv (tidy long format) and writes bristol-trends.js,
# a self-contained data file the trend dashboard reads (works over file://).
#
#   CSV columns: indicator,indicator_label,area,year,value,unit,source,source_url
#                (+ optional: notes, category, direction, format)
#
# Output shape:
#   window.BRISTOL_TRENDS = {
#     updated: "...",
#     indicators: [
#       { id, label, unit, source, source_url, notes, category, direction, format,
#         years:[...], bristol:[...], england:[...] }
#     ]
#   }
# =============================================================================
import csv, json, sys
from collections import defaultdict

CSV = "bristol_trends.csv"
OUT = "bristol-trends.js"
UPDATED = "July 2026"

# id -> (category, direction, format). direction: "up_good" | "down_good" | "neutral"
# category groups the cards on the page.
META = {
    "employment":  ("Work & income",       "up_good",   "pct"),
    "pay":         ("Work & income",       "up_good",   "gbp"),
    "quals_l4":    ("Education & skills",   "up_good",   "pct"),
    "quals_none":  ("Education & skills",   "down_good", "pct"),
    "gdhi":        ("Work & income",       "up_good",   "gbp"),
    "child_pov":   ("Work & income",       "down_good", "pct"),
    "ks2_rwm":     ("Education & skills",   "up_good",   "pct"),
    "attainment8": ("Education & skills",   "up_good",   "num"),
    "progress8":   ("Education & skills",   "up_good",   "num2"),
    "eyfsp_gld":   ("Education & skills",   "up_good",   "pct"),
    "absence":     ("Education & skills",   "down_good", "pct"),
    "suspensions": ("Education & skills",   "down_good", "num"),
    "le_male":     ("Health & wellbeing",  "up_good",   "yrs"),
    "le_female":   ("Health & wellbeing",  "up_good",   "yrs"),
}

def num(x):
    try:
        return round(float(x), 2)
    except (TypeError, ValueError):
        return None

def main():
    rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
    inds = {}
    order = []
    for r in rows:
        iid = r["indicator"]
        if iid not in inds:
            inds[iid] = {
                "id": iid,
                "label": r["indicator_label"],
                "unit": r["unit"],
                "source": r["source"],
                "source_url": r["source_url"],
                "notes": r.get("notes", "") or "",
                "b": {}, "e": {},   # year -> value
            }
            order.append(iid)
        yr = int(float(r["year"]))
        v = num(r["value"])
        if v is None:
            continue
        area = r["area"].strip().lower()
        if area.startswith("bristol"):
            inds[iid]["b"][yr] = v
        else:  # England / mean / benchmark
            inds[iid]["e"][yr] = v

    out = []
    for iid in order:
        d = inds[iid]
        present = sorted(set(d["b"]) | set(d["e"]))
        # fill every integer year across the span so real gaps (COVID, framework
        # breaks) render as breaks in the line rather than being silently closed
        years = list(range(present[0], present[-1] + 1)) if present else []
        cat, direction, fmt = META.get(iid, ("Other", "neutral", "num"))
        out.append({
            "id": d["id"], "label": d["label"], "unit": d["unit"],
            "source": d["source"], "source_url": d["source_url"],
            "notes": d["notes"], "category": cat, "direction": direction, "format": fmt,
            "years": years,
            "bristol": [d["b"].get(y) for y in years],
            "england": [d["e"].get(y) for y in years],
        })

    payload = {"updated": UPDATED, "indicators": out}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* AUTO-GENERATED by build_trends_js.py from bristol_trends.csv. Do not edit by hand. */\n")
        f.write("window.BRISTOL_TRENDS = ")
        json.dump(payload, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    print(f"wrote {OUT}: {len(out)} indicators ({', '.join(order)})")

if __name__ == "__main__":
    main()
