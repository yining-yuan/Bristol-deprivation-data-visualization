#!/usr/bin/env python3
# =============================================================================
# build_comparators_js.py
# Reads highest.csv / lowest.csv / london.csv / manchester.csv and emits
# bristol-comparators.js  ->  window.BRISTOL_COMPARATORS
#
# Per indicator id:
#   { unit, gap, ward, eng, highest:{area,v,v2,v2lab,note}, lowest, london, manchester }
#   - standard indicator: v = value, v2 = null
#   - gap indicator:      v = disadvantaged, v2 = peers        (v2lab 'peers')
#   - ward indicator:     highest/lowest -> single national extreme ward;
#                         london/manchester -> v = highest ward, v2 = lowest ward
#                                              (v2lab 'low ward')
# Plus an ALIAS map so the ee_*/ey_*/housing card ids reuse a comparator key.
# =============================================================================
import csv, json

GROUPS = ["highest", "lowest", "london", "manchester"]
GAP  = {"eyfsp_gap", "ks2_gap", "gcse5_em", "progress8"}
WARD = {"degree_ward", "child_pov_ward", "he_part"}   # multi-ward hi/lo in London/Manchester

# England (or England-disadvantaged for gaps) reference for London/Manchester shading.
ENG = {
 "eyfsp_gld":68.3, "phonics":80, "ks2_rwm":63, "prim_oo":91.6, "attainment8":46.0,
 "absence":20.0, "suspensions":11.31, "neet":3.4, "he_prog":28.9,
 "quals_l4":33.9, "quals_none":18.1, "ee_overcrowd":4.37, "ee_deprived":3.94,
 "eyfsp_gap":51.3, "ks2_gap":47,   # England disadvantaged level
}

# card id (as used in the .js indicator arrays) -> comparator key
ALIAS = {
 # education early-subpage
 "ee_gld":"eyfsp_gld", "ee_ready":"eyfsp_gap", "ee_access":"early_access",
 "ee_childpov":"child_pov_ward", "ee_overcrowd":"ee_overcrowd", "ee_deprived":"ee_deprived",
 # housing early-subpage
 "ey_overcrowd":"ee_overcrowd", "ey_deprived":"ee_deprived", "ey_childpov":"child_pov_ward",
 "ey_earlyaccess":"early_access", "ey_ready":"eyfsp_gap",
 # housing main indicators
 "overcrowd":"ee_overcrowd", "deprived_34":"ee_deprived", "child_pov":"child_pov_ward",
}

def num(s):
    s = (s or "").strip()
    if s == "":
        return None
    try:
        f = float(s)
        return int(f) if f == int(f) else f
    except ValueError:
        return None

def short_area(a):
    a = a.split(" — ")[0].strip()
    if a.startswith("London (region)") or a == "London":
        return "London"
    return a

def load(group):
    rows = {}
    with open(f"{group}.csv", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows.setdefault(r["indicator"], []).append(r)
    return rows

def main():
    data = {g: load(g) for g in GROUPS}
    ids = []
    for g in GROUPS:
        for k in data[g]:
            if k not in ids:
                ids.append(k)

    OUT = {}
    for iid in ids:
        unit = None
        entry = {"gap": 1 if iid in GAP else 0, "ward": 1 if iid in WARD else 0,
                 "eng": ENG.get(iid)}
        for g in GROUPS:
            rlist = data[g].get(iid, [])
            if not rlist:
                entry[g] = {"area": "n/a", "v": None, "v2": None, "v2lab": None, "note": ""}
                continue
            unit = unit or rlist[0]["unit"]
            r0 = rlist[0]
            v = num(r0["value"])
            area = short_area(r0["area"])
            v2 = None; v2lab = None
            if iid in GAP and len(rlist) >= 2:
                v2 = num(rlist[1]["value"]); v2lab = "peers"
            elif iid in WARD and g in ("london", "manchester") and len(rlist) >= 2:
                v2 = num(rlist[1]["value"]); v2lab = "low ward"
            entry[g] = {"area": area, "v": v, "v2": v2, "v2lab": v2lab, "note": r0["notes"]}
        entry["unit"] = unit or "%"
        OUT[iid] = entry

    payload = {"DATA": OUT, "ALIAS": ALIAS}
    js = ("/* AUTO-GENERATED by build_comparators_js.py — do not edit by hand.\n"
          "   Comparator geographies (highest/lowest English LA, London region,\n"
          "   Manchester LA) for each indicator. See the four *.csv files. */\n"
          "window.BRISTOL_COMPARATORS = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n")
    with open("bristol-comparators.js", "w", encoding="utf-8") as f:
        f.write(js)
    print(f"wrote bristol-comparators.js: {len(OUT)} indicators, {len(ALIAS)} aliases")

if __name__ == "__main__":
    main()
